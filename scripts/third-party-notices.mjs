// Writes THIRD_PARTY_NOTICES.md: the licences of everything bundled into the
// released `halcyon` package (server bundle and built web UI). Run after
// `pnpm install`; re-run when a bundled dependency changes.
//   node scripts/third-party-notices.mjs
import { existsSync, readFileSync, readdirSync, realpathSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = fileURLToPath(new URL('..', import.meta.url));

// [package, resolved from (a workspace folder, or the package that depends on it), purpose].
// Keep in step with what the release bundles: the server's runtime dependencies, and the
// web UI's runtime (Svelte, SvelteKit's client and its helpers) plus the self-hosted fonts.
const BUNDLED = [
	['hono', 'packages/server', 'HTTP framework (server bundle)'],
	['@hono/node-server', 'packages/server', 'Node.js adapter for Hono (server bundle)'],
	['svelte', 'apps/web', 'UI framework runtime (web UI)'],
	['@sveltejs/kit', 'apps/web', 'Application framework client runtime (web UI)'],
	['devalue', '@sveltejs/kit', 'Serialisation, used by the SvelteKit client (web UI)'],
	['esm-env', 'svelte', 'Environment flags, used by Svelte (web UI)'],
	['clsx', 'svelte', 'Class name helper, used by Svelte (web UI)'],
	['@fontsource-variable/geist', 'apps/web', 'Geist typeface (web UI)'],
	['@fontsource-variable/geist-mono', 'apps/web', 'Geist Mono typeface (web UI)']
];

const resolved = new Map();
function packageDir(name, from) {
	// pnpm links a package's dependencies next to it, in the node_modules folder that contains it.
	const base = resolved.has(from)
		? join(resolved.get(from), from.startsWith('@') ? '../..' : '..')
		: join(root, from, 'node_modules');
	const dir = join(base, name);
	if (!existsSync(join(dir, 'package.json'))) throw new Error(`Cannot find ${name} from ${from}; run pnpm install`);
	const real = realpathSync(dir);
	resolved.set(name, real);
	return real;
}

const sections = BUNDLED.map(([name, from, purpose]) => {
	const dir = packageDir(name, from);
	const pkg = JSON.parse(readFileSync(join(dir, 'package.json'), 'utf8'));
	const file = readdirSync(dir).find((f) => /^(licen[cs]e|copying)(\.(md|txt))?$/i.test(f));
	if (!file) throw new Error(`No licence file in ${name}`);
	const text = readFileSync(join(dir, file), 'utf8').trim();
	const home = typeof pkg.repository === 'string' ? pkg.repository : pkg.repository?.url ?? pkg.homepage ?? '';
	return [
		`## ${name} ${pkg.version}`,
		'',
		`${purpose}. Licence: ${pkg.license}.${home ? ` Source: ${home.replace(/^git\+/, '').replace(/\.git$/, '')}` : ''}`,
		'',
		'```text',
		text,
		'```'
	].join('\n');
});

const out = [
	'# Third-party notices',
	'',
	'The released `halcyon` package bundles the following third-party software and fonts. Each is used under its own licence, reproduced below. Development-only tools (TypeScript, Vite, Vitest, esbuild and others) are not distributed and are not listed.',
	'',
	'This file is generated by `node scripts/third-party-notices.mjs`.',
	'',
	...sections.flatMap((s) => [s, ''])
].join('\n');

writeFileSync(join(root, 'THIRD_PARTY_NOTICES.md'), out);
console.log(`Wrote THIRD_PARTY_NOTICES.md (${BUNDLED.length} packages)`);
