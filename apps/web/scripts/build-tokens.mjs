#!/usr/bin/env node
// Generates src/lib/design/tokens.css from the vendored design-system tokens.json.
// Run with `pnpm --filter web tokens` after re-vendoring tokens.json.
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const dir = join(dirname(fileURLToPath(import.meta.url)), '..', 'src', 'lib', 'design');
const tokens = JSON.parse(readFileSync(join(dir, 'tokens.json'), 'utf8'));

const light = [];
const dark = [];
const fixed = [];

const themed = (name, value) => {
	if (value && typeof value === 'object') {
		light.push(`  --${name}: ${value.light};`);
		dark.push(`  --${name}: ${value.dark};`);
	} else {
		fixed.push(`  --${name}: ${value};`);
	}
};

for (const t of tokens.color.tokens) themed(t.name, t.value);
for (const t of tokens.shadow.tokens) themed(t.name, t.value);
fixed.push(`  --font-sans: ${tokens.type.families.sans};`);
fixed.push(`  --font-mono: ${tokens.type.families.mono};`);
for (const family of ['spacing', 'radius', 'size', 'opacity', 'zIndex']) {
	for (const t of tokens[family].tokens) fixed.push(`  --${t.name}: ${t.value};`);
}

const css = `/* Generated by scripts/build-tokens.mjs from tokens.json (Halcyon design system v${tokens.version}).
   Do not edit by hand. Light is the default; dark follows the OS unless
   <html data-theme="light|dark"> overrides it. */
:root {
  color-scheme: light;
${fixed.join('\n')}
${light.join('\n')}
}
@media (prefers-color-scheme: dark) {
  :root:not([data-theme="light"]) {
    color-scheme: dark;
${dark.map((l) => '  ' + l).join('\n')}
  }
}
:root[data-theme="dark"] {
  color-scheme: dark;
${dark.join('\n')}
}
`;

writeFileSync(join(dir, 'tokens.css'), css);
console.log(`tokens.css: ${light.length} themed, ${fixed.length} fixed variables`);
